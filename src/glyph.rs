/// Look up the glyph index for a BMP codepoint, falling back to BLANK for unknown.
pub fn index_for(cp: u32) -> u8 {
    for &(k, v) in GLYPH_TABLE {
        if k == cp { return v; }
    }
    0
}

#[inline]
pub const fn bitmap_width() -> usize { 24 }
#[inline]
pub const fn bitmap_height() -> usize { 24 }

/// Render a glyph into the framebuffer at sub-pixel position (fx, fy), scaled by `scale`.
/// `fx`/`fy` are in pixel coordinates with 8 fractional bits (Q8 fixed-point: 256 = 1 px).
pub fn draw_glyph(
    fb: &mut [u32], w: usize, h: usize,
    glyph_idx: u8, color: u32, glow: u32,
    fx: i32, fy: i32, scale_q8: u32,
    alpha: f32,
) {
    if alpha <= 0.0 { return; }
    let bm = &FONT[glyph_idx as usize];
    // Compute screen-space bounding box (covers all bitmap pixels that map inside the framebuffer).
    let gw = (bitmap_width() as u32 * scale_q8) >> 8;
    let gh = (bitmap_height() as u32 * scale_q8) >> 8;
    let ix = fx >> 8;
    let iy = fy >> 8;
    let x0 = ix.max(0) as usize;
    let y0 = iy.max(0) as usize;
    let x1 = (ix + gw as i32).min(w as i32) as usize;
    let y1 = (iy + gh as i32).min(h as i32) as usize;
    if x0 >= x1 || y0 >= y1 { return; }

    for sy in y0..y1 {
        // Source bitmap row (in 24-bit units), inverted so glyph appears upright.
        let bmy = (((sy - 24) as i32 - iy) * 256) / scale_q8 as i32;
        if bmy < 0 || bmy >= 24 { continue; }
        let row = &bm[bmy as usize];
        for sx in x0..x1 {
            let bmx = ((sx as i32 - ix) * 256) / scale_q8 as i32;
            if bmx < 0 || bmx >= 24 { continue; }
            let byte = bmx / 8;
            let bit  = 7 - (bmx % 8);
            let cov = if (row[byte as usize] >> bit) & 1 == 1 { 1.0 } else { 0.0 };
            if cov > 0.0 {
                let px = &mut fb[sy * w + sx];
                *px = color::blend_over_lin(*px, color, alpha * cov);
            }
        }
    }
    // Soft outer glow: a small additive splat around the glyph bbox.
    if alpha > 0.4 {
        let glow_amt = alpha * 0.18;
        let gx0 = (ix - 8).max(0) as usize;
        let gy0 = (iy - 8).max(0) as usize;
        let gx1 = (ix + gw as i32 + 8).min(w as i32) as usize;
        let gy1 = (iy + gh as i32 + 8).min(h as i32) as usize;
        for sy in gy0..gy1 {
            for sx in gx0..gx1 {
                let dx = (sx as i32 - ix - gw as i32 / 2) as f32;
                let dy = (sy as i32 - iy - gh as i32 / 2) as f32;
                let d2 = dx * dx + dy * dy;
                let falloff = (1.0 / (1.0 + d2 * 0.002)).clamp(0.0, 1.0);
                if falloff > 0.01 {
                    let px = &mut fb[sy * w + sx];
                    *px = color::blend_add_lin(*px, glow, glow_amt * falloff);
                }
            }
        }
    }
}